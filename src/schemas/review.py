from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field


class Severity(str, Enum):
    INFO = "INFO"
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class PRLabel(str, Enum):
    BUG_FIX = "bug: Fixes an existing issue or bug"
    FEATURE = "feature: Adds new functionality"
    DEPENDENCY = "dependencies: Updates or adds packages/libraries"
    DOCUMENTATION = "documentation: Improves docs, README, comments"
    REFACTOR = "refactor: Code cleanup without behavior change"
    TEST = "testing: Adds or improves test coverage"
    PERFORMANCE = "performance: Speed/efficiency improvements"
    STYLE = "style: Formatting, linting, code style"
    TRANSLATION = "i18n: i18n or language additions"
    CONFIG = "config: Config file or environment changes"
    SECURITY = "security: Patches, auth, vulnerability fixes"
    DEPRECATION = "deprecation: Removes or phases out old code"

    @property
    def clean_name(self) -> str:
        """Returns clean category name for GitHub label API (e.g. 'security')."""
        return self.value.split(":")[0]

    @property
    def emoji_name(self) -> str:
        """Returns emoji + short description for Markdown summaries."""
        return self.value.split(":")[1].strip()


class ReviewFinding(BaseModel):
    file_path: str = Field(..., description="Target file path relative to repo root")
    line_number: Optional[int] = Field(
        None, description="Exact line number in diff where issue occurs"
    )
    title: str = Field(..., description="Short summary of the finding")
    severity: Severity = Field(..., description="Vulnerability or issue severity level")
    description: str = Field(
        ...,
        description="Detailed technical explanation of the bug or architectural flaw",
    )
    suggestion: Optional[str] = Field(
        None, description="Suggested refactored code snippet or fix"
    )


class AgentReviewReport(BaseModel):
    agent_name: str = Field(
        ..., description="Name of the sub-agent (e.g., 'SecurityAgent')"
    )
    passed: bool = Field(
        ..., description="False if critical issues require blocking the PR"
    )
    findings: List[ReviewFinding] = Field(default_factory=list)
    summary: str = Field(
        ..., description="Executive summary formatted for GitHub Markdown"
    )


class FinalPRReview(BaseModel):


    """Output generated by the Synthesizer agent combining all sub-agents."""

    labels: List[PRLabel] = Field(
        default_factory=list,
        description="Categorized labels applicable to this PR diff",
    )
    overall_passed: bool = Field(
        ..., description="False if any sub-agent found blocking issues"
    )
    markdown_summary: str = Field(
        ..., description="Final merged comment string ready for GitHub API"
    )
    inline_findings: List[ReviewFinding] = Field(
        default_factory=list,
        description="Individual inline line-level comments to post on the PR diff",
    )